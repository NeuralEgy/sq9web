// ============================================================
// القيادة — المؤسِّس ومجلس الإدارة.
//
// 🔴🔴 الملف ده فاضي عن قصد، وده مش نسيان.
//
//    square9.eg ما نشرش ولا اسم واحد: لا مؤسس، لا رئيس مجلس، لا
//    عضو منتدب، لا مدير. فأي اسم يتكتب هنا لازم ييجي **من العميل
//    بالإيد**، مش من بحث ولا من لينكدإن ولا من تخمين.
//
//    السبب أخطر من قاعدة الأسعار. سعر غلط بيضيّع صفقة؛ اسم أو
//    منصب غلط ده نشر بيانات غلط عن إنسان حقيقي على موقع شركة —
//    وممكن يتقري منه التزام قانوني على الشخص ده.
//
// الملف فيه خانتين مستقلتين: المؤسِّس (جواب بصوته) ومجلس الإدارة
// (أسامي ومناصب). كل واحدة بتظهر لوحدها أول ما تتملا — يعني لو
// وصل اسم المؤسِّس بس، القسم بتاعه يظهر والمجلس يفضل مخفي.
//
// ============================================================
// ١) المؤسِّس
// ============================================================
//
// اللي محتاجينه من العميل:
//
//   name      الاسم كامل زي ما هو بيكتبه هو (بالإنجليزي — الموقع إنجليزي)
//   role      المنصب بالظبط (Founder · Chairman · Managing Director…)
//   photo     صورة، 1200px عرض على الأقل، تتحط في
//             public/images/leadership/ والمسار يتكتب هنا
//   letter    كلامه هو، فقرة أو تلاتة
//
// وعن الـletter بالذات — دي الحتة اللي بتفرق. خليها تجاوب على
// التلاتة دول، بصوته هو مش بصوت شركة:
//
//   ١. ليه بنى الشركة؟ إيه اللي شافه في الغردقة وضايقه أو عجبه؟
//   ٢. القرار اللي كلّفه فلوس وخده بردو؟ (الـ٤٠٪ لاندسكيب مثال
//      جاهز — مسطح اتقرر ما يتبناش وما يتباعش)
//   ٣. المشتري اللي بيشتري على الخريطة لتسليم ٢٠٢٨ بيثق فيه ليه؟
//
// 🔴 اللي ما يتكتبش في الـletter: مفيش سنين خبرة، ولا عدد مشاريع
//    متسلّمة، ولا جوايز، ولا «رائد في السوق» — ولا واحدة منهم
//    منشورة، والقسم ده مش استثناء من قاعدة الموقع. لو العميل بعت
//    رقم من دول، يتسنده الأول (ترخيص · مشروع بالاسم · شهادة)،
//    وبعدين يتكتب.
//
// التوقيع تحت الجواب بيتولّد من name و role — ما تكتبهوش في النص.
// ============================================================

export type Founder = {
  name: string;
  role: string;
  /** مسار جوّه public/ — مثال: /images/leadership/founder.jpg */
  photo: string;
  /** كلامه. فقرة لكل عنصر. **كده** بتبقى خط عريض. */
  letter: ReadonlyArray<string>;
};

/**
 * 🔴 null = مفيش بيانات متسلّمة. سيبها null لحد ما توصل.
 *
 * ما تحطش قيم مؤقتة ولا «Coming soon» ولا اسم تجريبي — الموقع
 * بيتنشر من نفس الفرع ده، وقسم قيادة فيه اسم مؤقت أسوأ بكتير من
 * قسم مش موجود.
 */
export const FOUNDER: Founder | null = null;

// ============================================================
// ٢) مجلس الإدارة
// ============================================================
//
// اللي محتاجينه لكل عضو:
//
//   name      الاسم كامل بالإنجليزي
//   role      المنصب في المجلس (Chairman · Board Member ·
//             Managing Director · Head of Sales…)
//   focus     سطر واحد: هو مسؤول عن إيه بالظبط. اختياري، وأحسن
//             يكون موجود — «Board Member» لوحدها ما بتقول للمشتري
//             حاجة.
//   photo     اختيارية. القسم بيرسم بطاقة من غير صورة لو مش موجودة،
//             فما تحطش صورة ستوك لحد ما الصورة الحقيقية توصل.
//
// 🔴 ترتيب الليستة هو الترتيب اللي بيظهر على الصفحة، وعلى موقع
//    شركة الترتيب ده بيتقري كتسلسل مناصب. فالترتيب يتاخد من
//    العميل مش من عندنا.
//
// 🔴 وممنوع نضيف عضو من مصدر تاني — لا لينكدإن، لا السجل التجاري،
//    لا خبر صحفي. عضو مجلس إدارة مذكور على موقع الشركة ده إقرار
//    منها؛ مش معلومة إحنا نجمّعها.
// ============================================================

export type BoardMember = {
  name: string;
  role: string;
  focus?: string;
  /** مسار جوّه public/ — مثال: /images/leadership/chairman.jpg */
  photo?: string;
};

/** 🔴 ليستة فاضية = مفيش أسامي متسلّمة. سيبها فاضية لحد ما توصل. */
export const BOARD: ReadonlyArray<BoardMember> = [];

// ============================================================
// الأسئلة اللي الصفحات بتسألها قبل ما ترسم
// ============================================================

export const HAS_FOUNDER = FOUNDER !== null;
export const HAS_BOARD = BOARD.length > 0;

/**
 * هل في حاجة نعرضها على /leadership خالص؟
 *
 * الصفحة بترد 404 وهي false، والمسار ما بيدخلش المنيو ولا الخريطة.
 * أول ما أي واحدة من الخانتين تتملا، الصفحة بتشتغل لوحدها.
 */
export const HAS_LEADERSHIP = HAS_FOUNDER || HAS_BOARD;
